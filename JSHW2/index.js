//Работа с комбинированными операторами
let variable = 0; //variable = 0
// Увеличьте значение переменной на 7
variable += 7; //variable = 7
// Увеличьте значение переменной в 4 раза
variable *= 4; //variable = 28
// Уменьшите значение переменной на 8
variable -= 8; //variable = 20
// Разделите значение переменной на 4
variable /= 4; //variable = 5
// Возведите значение переменной в 3 степень
variable **= 3; //variable = 125
// Найдите остаток от деления переменной на 5
variable %= 5; //variable = 0
console.log(`Итоговое значение переменной: ${variable}`);


//Сравнение значений
// Числовые значения сравниваются обычным арифметическим способом
console.log(5 > 4); // true, потому что число 5 больше числа 4
// Строковые значения сравниваются по правилам Unicode
console.log("ананас" > "яблоко"); // false, поскольку первая буква "а" идет раньше первой буквы "я" в Unicode-коде
// Строки также сравниваются посимвольно
console.log("2" > "12"); // true, хотя визуально кажется иначе, но символьное сравнение показывает, что символ '2' больше символа '1'
// Нестрогое равенство позволяет сравнивать объекты разных типов с неявным приведением типа
console.log(undefined == null); // true, undefined и null рассматриваются равными при нестрогом сравнении
// Строгое равенство проверяет и тип, и значение одновременно
console.log(undefined === null); // false, потому что undefined и null имеют разные типы данных
// Строка "0" не равна значению null даже при нестрогом сравнении
console.log(null == "0"); // false, неявное преобразование не выполняется
// Значение null тоже не равно числу 0, даже при принудительном приведении строки к числу
console.log(null === +"0"); // false, несмотря на то, что "+" превращает строку "0" в число 0, оно всё равно отличается типом от null
                            

//Работа с побитовыми операциями
// Объявляем переменную a и присваиваем ей значение 5 (бинарное представление: 101)
const a = 5; 
// Объявляем переменную b и присваиваем ей значение 3 (бинарное представление: 011)
const b = 3; 

// Побитовая операция AND (&). Возвращает единицу там, где оба бита равны 1
console.log(a & b); // 1 (001), т.к. только последний бит совпадает (1&1=1)
// Побитовая операция OR (|). Возвращает единицу там, где хотя бы один бит равен 1
console.log(a | b); // 7 (111), т.к. любые единицы объединяются (1|1=1, 0|1=1, 1|0=1)
// Побитовая операция XOR (^). Возвращает единицу там, где биты различаются
console.log(a ^ b); // 6 (110), т.к. единица ставится там, где биты отличаются (1^1=0, 0^1=1, 1^0=1)
// Побитовая операция NOT (~). Инвертирует все биты числа (добавляется минус для чисел)
console.log(~a); // -6, т.к. ~5 (-6) в дополнительном коде становится отрицательным числом
// Побитовый сдвиг влево (<<). Все биты сдвигаются влево на указанное количество позиций
console.log(a << 1); // 10 (1010), сдвигаем 101 на одну позицию влево → получаем 1010 (десятичное 10)
// Побитовый сдвиг вправо (>>). Все биты сдвигаются вправо на указанное количество позиций
console.log(b >> 1); // 1 (001), сдвигаем 011 на одну позицию вправо → получаем 001 (десятичное 1)


//Пример на использование приоритетов
console.log(2 + 3 * 4); // 14, сначала умножение
console.log((2 + 3) + 2 * 4); // 13, сначала скобки 2+3=5, потом умножение 2*4=8, а затем общее сложение 5+8=13