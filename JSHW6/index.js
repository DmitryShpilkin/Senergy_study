//Работа с объектом "дни недели"
// Создание объекта, представляющего дни недели, где ключами выступают номера дней (1-7), а значениями — названия дней.
const weekDays = {
  1: "Понедельник",
  2: "Вторник",
  3: "Среда",
  4: "Четверг",
  5: "Пятница",
  6: "Суббота",
  7: "Воскресенье",
};

// Вывод всего объекта в консоль
console.log("Дни недели:", weekDays);
// Доступ к конкретному дню недели по номеру ключа
const day = weekDays[3]; // Получаем третий день недели ("Среда")
console.log("Третий день недели:", day);
// Удаление определенного дня из объекта
delete weekDays[7]; // Удаляем седьмой день ("Воскресенье")
// Вывод обновленного объекта в консоль
console.log("Обновленные дни недели:", weekDays);


//Использование Map
// Создание экземпляра класса Map с парами ключ-значение
// Каждая пара представляет номер дня и название дня недели
const weekDaysMap = new Map([
  [1, "Понедельник"], // Ключи — номера дней, значения — названия дней
  [2, "Вторник"],
  [3, "Среда"],
  [4, "Четверг"],
  [5, "Пятница"],
  [6, "Суббота"],
  [7, "Воскресенье"],
]);

// Вывод полного содержания карты в консоль
console.log("Дни недели (Map):", weekDaysMap);
// Получение конкретного дня недели по ключу (получаем значение по ключу 3)
console.log("Третий день недели (Map):", weekDaysMap.get(3)); // "Среда"
// Удаление пары из карты по указанному ключу (ключ 7 соответствует Воскресенью)
weekDaysMap.delete(7);
// Вывод обновленной карты после удаления
console.log("Обновленные дни недели (Map):", weekDaysMap);


//Использование Set
// Создание набора уникальных элементов (days of the week)
// Элементы будут уникальны даже при повторениях
const weekDaysSet = new Set([
  "Понедельник",
  "Вторник",
  "Среда",
  "Четверг",
  "Пятница",
  "Суббота",
  "Воскресенье",
]);

// Вывод полного содержания набора в консоль
console.log("Дни недели (Set):", weekDaysSet);
// Удаление конкретного элемента из набора
weekDaysSet.delete("Воскресенье"); // Удаляем воскресенье из набора
// Вывод обновленного набора
console.log("Обновленные дни недели (Set):", weekDaysSet);
// Проверка наличия конкретного элемента в наборе
console.log("Есть ли Среда в наборе?", weekDaysSet.has("Среда"));
// Вернет true, потому что среда присутствует в наборе


//Перебор Map и Set
// Перебираем каждую пару ключ-значение в Map с помощью метода forEach
weekDaysMap.forEach((value, key) => {
  // value — это значение (название дня недели)
  // key — это ключ (номер дня недели)
  console.log(`День ${key}: ${value}`); // Форматируем вывод с именем дня и его номером
});

// Перебор всех элементов в наборе (Set) с помощью метода forEach
weekDaysSet.forEach((day) => {
  // Параметр day — это текущее значение (день недели) на каждой итерации
  console.log(`День недели: ${day}`); // Выводим каждый день отдельно
});



//Преобразование между объектом, Map и Set
// Конвертация обычного объекта в карту (Map)
// Object.entries() превращает объект в массив пар ключ-значение
// Затем конструктор Map создаёт карту на основе этого массива
const mapFromObject = new Map(Object.entries(weekDays));
// Вывод полученной карты в консоль
console.log("Map из объекта:", mapFromObject);

// Преобразование набора (Set) в массив
// Метод Array.from() создаёт новый массив из любого iterable (перечислимого) объекта
const arrayFromSet = Array.from(weekDaysSet);
// Вывод полученного массива в консоль
console.log("Массив из Set:", arrayFromSet);
