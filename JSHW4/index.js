//Скрипт: числа от 1 до 100, кратные 3, 5 или 3 и 5 одновременно
// Цикл от 1 до 100 включительно
for (let i = 1; i <= 100; i++) {
  // Проверяем, делится ли число на 3 и 5 одновременно
  if (i % 3 === 0 && i % 5 === 0) {
    console.log(`Число ${i} кратно 3 и 5 одновременно`); // выводим сообщение
  } 
  // Если делится только на 3
  else if (i % 3 === 0) {
    console.log(`Число ${i} кратно 3`); // выводим сообщение
  } 
  // Если делится только на 5
  else if (i % 5 === 0) {
    console.log(`Число ${i} кратно 5`); // выводим сообщение
  } 
  // Если ни одно условие не выполнено
  else {
    console.log(`Число ${i}`); // просто выводим само число
  }
}


//Скрипт: числа Армстронга
// Перебираем числа от 100 до 999
for (let num = 100; num <= 999; num++) {
  // Преобразуем число в массив цифр (каждая цифра становится отдельным элементом)
  const digits = num.toString().split('').map(Number);
  // Вычисляем сумму кубов каждой цифры числа
  const sumOfCubes = digits.reduce((sum, digit) => sum + digit ** 3, 0);
  // Проверяем, равно ли исходное число сумме кубов его цифр
  if (sumOfCubes === num) {
    // Если да, выводим сообщение о найденном числе Армстронга
    console.log(`Число Армстронга: ${num}`);
  }
}


//Скрипт: наибольший общий делитель (НОД)
const a = 56; // Объявление первого числа
const b = 98; // Объявление второго числа
let gcd = 1; // Переменная для хранения наибольшего общего делителя (НОД), инициализирована единицей
const min = Math.min(a, b); // Определяем наименьшее из двух чисел, поскольку максимальный возможный НОД не больше меньшего числа
// Проходим циклом от 1 до минимального значения среди a и b
for (let i = 1; i <= min; i++) {
  // Проверяем, является ли текущее число общим делителем обоих чисел
  if (a % i === 0 && b % i === 0) { // Если оба числа делятся нацело на текущее число
    gcd = i; // Запоминаем последнее общее делимое, оно автоматически станет наибольшим общим делителем
  }
}
// Вывод результата в консоль
console.log(`Наибольший общий делитель чисел ${a} и ${b}: ${gcd}`);


//Оптимизация алгоритма для НОД
// Заданные числа
let c = 3; // Первое число
let d = 78; // Второе число

// Основной цикл Евклидова алгоритма
while (d !== 0) { // пока d не равно нулю
  let temp = d;     // временно сохраняем текущее значение d
  d = c % d;       // обновляем d, делая его равным остатку от деления c на d
  c = temp;        // обновляем c, делая его равным старому значению d
}
// По завершении цикла, a хранит НОД чисел
console.log(`Наибольший общий делитель чисел 3 и 78: ${c}`); // выводит НОД чисел 3 и 78


//Дополнительный скрипт: сумма всех чисел диапазона
let sum = 0;                     // Инициализируем переменную sum, в которой будем хранить сумму

for (let i = 1; i <= 100; i++) { // Начинаем цикл от 1 до 100 включительно
  sum += i;                      // Добавляем текущее число i к общей сумме
}

console.log(`Сумма всех чисел от 1 до 100: ${sum}`); // Выводим итоговую сумму в консоль