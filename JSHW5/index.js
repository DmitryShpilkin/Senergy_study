//Изменение строки: "luke, I am your father" → "Luke, I am your father"
// Исходная строка
const sentence = "luke, I am your father";
// Создаем новую строку, заменяя первый символ исходной строки на заглавную букву,
// используя метод charAt() для извлечения первого символа и toUpperCase() для перевода его в верхний регистр.
// Затем добавляем остальную часть строки, начиная со второго символа (индекс 1),
// используя метод slice().
const updatedSentence = sentence.charAt(0).toUpperCase() + sentence.slice(1);
// Выводим обновленную строку в консоль
console.log(updatedSentence); // "Luke, I am your father"


//Сравнение строк
const str1 = "AbcdEfg"; // Первая строка
const str2 = "abCDEFg"; // Вторая строка
// Прямое сравнение строк без изменения регистра символов
console.log(`Первое сравнение: ${str1 === str2}`); // Результат: false, так как строки различаются по регистру букв
// Приводим обе строки к верхнему регистру перед сравнением
const upperStr1 = str1.toUpperCase(); // Преобразуем первую строку в верхний регистр
const upperStr2 = str2.toUpperCase(); // Преобразуем вторую строку в верхний регистр
// Теперь сравниваем строки, приведённые к одному регистру
console.log(`Второе сравнение: ${upperStr1 === upperStr2}`); // Результат: true, так как теперь строки совпадают по содержимому


//Определение високосных лет
// Массив лет
const years = [2000, 2001, 2002, 2003, 2004, 2005];
// Фильтруем массив, оставляя только високосные годы
// Условие проверки високосного года:
// Год является високосным, если выполняется одно из двух условий:
// 1. Год делится нацело на 4, НО не делится на 100
// 2. Или же год делится нацело на 400
const leapYears = years.filter((year) =>
  (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0);
// Выводим список високосных годов
console.log(`Високосные годы: ${leapYears}`); // [2000, 2004]


//Сортировка и реверс массива
const numbers = [6, 187, 66, 4, 67, 30, 18];
// Сортировка чисел по возрастанию
// sort принимает функцию обратного вызова, которая определяет порядок сортировки
// Здесь используется оператор '<' для правильной числовой сортировки
const sortedNumbers = [...numbers].sort((a, b) => a - b);
console.log(`Отсортированный массив: ${sortedNumbers}`);
// [4, 6, 18, 30, 66, 67, 187]
// Обращение порядка элементов отсортированного массива
const reversedNumbers = [...sortedNumbers].reverse();
console.log(`Обратный массив: ${reversedNumbers}`);
// [187, 67, 66, 30, 18, 6, 4]


//Сумма всех элементов массива(ч использованием for, а не reduce)
// Исходный массив чисел
const anotherNumbers = [6, 187, 66, 4, 67, 30, 18];
// Переменная для хранения общей суммы
let sum = 0;
// Проходим циклом по каждому элементу массива
for (let i = 0; i < anotherNumbers.length; i++) {
  // Добавляем каждый элемент к сумме
  sum += anotherNumbers[i];
}
// Выводим результат
console.log(`Сумма элементов массива: ${sum}`); // 378


//Преобразование массива строк
// Исходный массив строк
const strings = ["apple", "banana", "cherry"];
// Применение map для трансформации каждой строки
// Внутри колбэк-функции используем метод charAt(), чтобы получить первый символ строки
// Далее применяем toUpperCase(), чтобы сделать его заглавным
// К первому символу присоединяем оставшуюся часть строки, используя slice(1)
const capitalizedStrings = strings.map((str) =>
  str.charAt(0).toUpperCase() + str.slice(1));
// Вывод преобразованного массива
console.log(capitalizedStrings); // ["Apple", "Banana", "Cherry"]